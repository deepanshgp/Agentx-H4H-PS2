// Live self-learning loop (paper trading).
//
// Each cycle, for every watched asset the agent:
//   1. settles the PREVIOUS decision: measures the real price move, computes the reward/penalty,
//      and stores the transition in an on-policy experience buffer;
//   2. observes the current market, picks an action with its policy, and executes it on a paper account;
//   3. once enough fresh experience has accumulated, runs a PPO update — so the policy keeps
//      improving from its own real outcomes.
//
// Orders are PAPER only — nothing here touches the real portfolio or any exchange.

import {
  Account,
  AccountConfig,
  ACTIONS,
  applyAction,
  equityAt,
  markToMarket,
  newAccount,
  positionView,
} from "./account";
import { buildObservation, marketFeaturesAt, WARMUP } from "./features";
import { PPOAgent, Transition, UpdateStats } from "./ppo";
import { RewardBreakdown, RewardConfig, TradeInfo, computeReward } from "./rewards";
import type { RLAsset } from "./assets";
import type { LearningEvent, TradeMemoryEntry } from "./store";

export interface PendingDecision {
  obs: number[];
  action: number;
  logp: number;
  value: number;
  equityBefore: number;
  info: TradeInfo;
  price: number;
  ts: number;
}

export interface PricePoint {
  ts: number;
  price: number;
  action?: "BUY" | "SELL";
}

export interface EquityPoint {
  ts: number;
  equity: number;
}

export interface LiveAssetState {
  assetId: string;
  name: string;
  account: Account;
  pending: PendingDecision | null;
  /** Completed (settled) transitions awaiting the next PPO update, in time order. */
  trajectory: Transition[];
  lastPrice: number;
  lastAction: number | null;
  lastProbs: number[] | null;
  /** Recent price ticks with optional trade markers (capped at 200 points). */
  priceHistory: PricePoint[];
  /** Equity at each cycle (capped at 200 points). */
  equityHistory: EquityPoint[];
}

export interface LiveState {
  startedAt: number;
  assets: Record<string, LiveAssetState>;
  cycles: number;
  onlineUpdates: number;
  cumReward: number;
  settledDecisions: number;
  /** Agent update-count the buffered experience was generated under (staleness guard). */
  policyVersion: number;
}

export function newLiveState(agent: PPOAgent): LiveState {
  return {
    startedAt: Date.now(),
    assets: {},
    cycles: 0,
    onlineUpdates: 0,
    cumReward: 0,
    settledDecisions: 0,
    policyVersion: agent.updates,
  };
}

export interface LiveOptions {
  account: AccountConfig;
  reward: RewardConfig;
  /** Sample from the policy (true) or always take the most likely action (false). */
  explore: boolean;
  /** Update the policy from outcomes. */
  learn: boolean;
  /** Settled transitions required before running an online PPO update. */
  minBatch: number;
  /** Online learning-rate multiplier (conservative so live noise can't wreck the model). */
  lrScale: number;
}

export const DEFAULT_LIVE_OPTIONS = (account: AccountConfig, reward: RewardConfig): LiveOptions => ({
  account,
  reward,
  explore: true,
  learn: true,
  minBatch: 24,
  lrScale: 0.3,
});

export interface LiveDecision {
  assetId: string;
  name: string;
  action: (typeof ACTIONS)[number];
  probs: number[];
  price: number;
  equity: number;
  settled?: { reward: number; breakdown: RewardBreakdown };
  executed?: { side: "BUY" | "SELL"; price: number; value: number; realizedPct: number | null };
}

export interface LiveCycleOutput {
  decisions: LiveDecision[];
  events: Omit<LearningEvent, "id">[];
  memory: TradeMemoryEntry[];
  update: UpdateStats | null;
}

/**
 * Run one live cycle. `histories` maps asset id -> daily closes with the latest price LAST.
 * Mutates `state` and the agent (when learning).
 */
export function runLiveCycle(
  agent: PPOAgent,
  state: LiveState,
  assets: RLAsset[],
  histories: Record<string, number[]>,
  opts: LiveOptions
): LiveCycleOutput {
  const decisions: LiveDecision[] = [];
  const events: Omit<LearningEvent, "id">[] = [];
  const memory: TradeMemoryEntry[] = [];
  const now = Date.now();
  state.cycles += 1;

  // Drop experience generated by an older policy (e.g. after offline re-training / loading a model)
  if (state.policyVersion !== agent.updates) {
    for (const a of Object.values(state.assets)) {
      a.trajectory = [];
      a.pending = null;
    }
    state.policyVersion = agent.updates;
    events.push({ ts: now, kind: "info", message: "Policy changed since last cycle — discarded stale buffered experience." });
  }

  for (const asset of assets) {
    const prices = histories[asset.id];
    if (!prices || prices.length < WARMUP + 2) {
      events.push({ ts: now, kind: "warn", assetId: asset.id, message: `${asset.name}: not enough price history — skipped.` });
      continue;
    }
    const last = prices.length - 1;
    const price = prices[last];

    let st = state.assets[asset.id];
    if (!st) {
      st = {
        assetId: asset.id,
        name: asset.name,
        account: newAccount(opts.account),
        pending: null,
        trajectory: [],
        lastPrice: price,
        lastAction: null,
        lastProbs: null,
        priceHistory: [],
        equityHistory: [],
      };
      state.assets[asset.id] = st;
    }

    // 1) Settle the previous decision with the realised price move
    let settled: LiveDecision["settled"];
    if (st.pending) {
      const p = st.pending;
      markToMarket(st.account, price);
      const eqAfter = equityAt(st.account, price);
      const pv = positionView(st.account, price);
      const breakdown = computeReward(
        {
          equityBefore: p.equityBefore,
          equityAfter: eqAfter,
          peakEquity: st.account.peakEquity,
          unrealizedPct: pv.unrealizedPct,
          initialEquity: opts.account.initialCash,
          info: p.info,
        },
        opts.reward
      );
      st.trajectory.push({
        obs: p.obs,
        action: p.action,
        logp: p.logp,
        value: p.value,
        reward: breakdown.total,
        done: false,
        bootstrap: 0,
      });
      state.cumReward += breakdown.total;
      state.settledDecisions += 1;
      settled = { reward: breakdown.total, breakdown };
      events.push({
        ts: now,
        kind: "reward",
        assetId: asset.id,
        reward: breakdown.total,
        breakdown,
        message: `${asset.name}: ${ACTIONS[p.action]} → ${breakdown.total >= 0 ? "reward" : "penalty"} ${breakdown.total >= 0 ? "+" : ""}${breakdown.total.toFixed(2)}`,
      });
    }

    // 2) Observe + act
    const feats = marketFeaturesAt(prices, last);
    const obs = buildObservation(feats, positionView(st.account, price));
    const { action, logp, value, probs } = agent.act(obs, !opts.explore);
    const equityBefore = equityAt(st.account, price);
    const { info, trade } = applyAction(st.account, action, price, opts.account);

    st.pending = { obs, action, logp, value, equityBefore, info, price, ts: now };
    st.lastPrice = price;
    st.lastAction = action;
    st.lastProbs = probs;

    // ── history (capped at 200 points each) ──────────────────────────────────
    const HIST_CAP = 200;
    const pricePt: PricePoint = { ts: now, price };
    if (trade) pricePt.action = trade.action as "BUY" | "SELL";
    st.priceHistory = [...st.priceHistory, pricePt].slice(-HIST_CAP);
    st.equityHistory = [...st.equityHistory, { ts: now, equity: equityAt(st.account, price) }].slice(-HIST_CAP);

    const decision: LiveDecision = {
      assetId: asset.id,
      name: asset.name,
      action: ACTIONS[action],
      probs,
      price,
      equity: equityAt(st.account, price),
      settled,
    };
    if (trade) {
      decision.executed = { side: trade.action as "BUY" | "SELL", price: trade.price, value: trade.value, realizedPct: info.realizedPct };
      memory.push({
        id: `tm-${now}-${asset.id}`,
        ts: now,
        source: "live",
        assetId: asset.id,
        assetName: asset.name,
        side: trade.action as "BUY" | "SELL",
        price: trade.price,
        value: trade.value,
        realizedPct: info.realizedPct,
      });
    }
    decisions.push(decision);
  }

  // 3) Online PPO update from settled real outcomes
  let update: UpdateStats | null = null;
  if (opts.learn) {
    const settledCount = Object.values(state.assets).reduce((s, a) => s + a.trajectory.length, 0);
    if (settledCount >= opts.minBatch) {
      const batch: Transition[] = [];
      for (const a of Object.values(state.assets)) {
        if (!a.trajectory.length) continue;
        const traj = a.trajectory;
        // Trajectory is cut here: bootstrap from the value of the current (pending) state
        const boot = a.pending ? a.pending.value : 0;
        traj[traj.length - 1] = { ...traj[traj.length - 1], done: true, bootstrap: boot };
        batch.push(...traj);
      }
      const original = agent.cfg;
      agent.cfg = {
        ...original,
        lrActor: original.lrActor * opts.lrScale,
        lrCritic: original.lrCritic * opts.lrScale,
        epochs: Math.max(2, Math.min(original.epochs, 4)),
      };
      try {
        update = agent.update(batch, 0);
      } finally {
        agent.cfg = original;
      }
      state.onlineUpdates += 1;
      state.policyVersion = agent.updates;
      // Start fresh trajectories. A pending decision (made one step ago under the pre-update policy)
      // is kept: PPO's clipped ratio handles this one-step staleness safely.
      for (const a of Object.values(state.assets)) a.trajectory = [];
      events.push({
        ts: now,
        kind: "update",
        stats: update,
        message: `PPO online update #${state.onlineUpdates} on ${batch.length} real outcomes — entropy ${update.entropy.toFixed(2)}, KL ${update.approxKL.toFixed(4)}`,
      });
    }
  }

  return { decisions, events, memory, update };
}

/** Total paper equity across all live asset slots, and the capital they started with. */
export function liveEquity(state: LiveState, initialPerAsset: number): { equity: number; initial: number; returnPct: number } {
  let equity = 0;
  let initial = 0;
  for (const a of Object.values(state.assets)) {
    equity += equityAt(a.account, a.lastPrice);
    initial += initialPerAsset;
  }
  return { equity, initial, returnPct: initial > 0 ? equity / initial - 1 : 0 };
}
